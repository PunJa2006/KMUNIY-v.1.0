export const LANGUAGE_KEY = 'community-language';
export function getLanguage() {
  try { return localStorage.getItem(LANGUAGE_KEY) === 'th' ? 'th' : 'en'; } catch { return 'en'; }
}
export function setLanguage(language) {
  if (!['th', 'en'].includes(language)) throw new Error('Unsupported language');
  localStorage.setItem(LANGUAGE_KEY, language);
}
export function dateLocale(language = getLanguage()) { return language === 'en' ? 'en-US' : 'th-TH'; }
export function t(source, values = {}, language = getLanguage()) {
  let template = source;
  if (language === 'en') {
    template = english[source] || (english[source.trim()] ? source.match(/^\s*/)[0] + english[source.trim()] + source.match(/\s*$/)[0] : source);
    for (const [unit, name] of [['second', 'seconds'], ['day', 'days'], ['post', 'count'], ['comment', 'count']]) template = template.replaceAll(unit + '(s)', unit + (Number(values[name]) === 1 ? '' : 's'));
  }
  return template.replace(/\{([a-zA-Z]+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}
export function localizeError(message, language = getLanguage()) {
  if (typeof message !== 'string' || language === 'th') return message;
  if (english[message]) return t(message, {}, language);
  const wait = message.match(/^กรุณารออีก (\d+) วินาทีก่อนโพสต์ถัดไป$/);
  if (wait) return t('กรุณารออีก {seconds} วินาทีก่อนโพสต์ถัดไป', {seconds: Number(wait[1])}, language);
  const date = message.match(/^(@username|ชื่อเล่น)\s*เปลี่ยนได้อีกครั้งวันที่ (.+)$/);
  if (date) {
    const readable = date[2].replace(/(\d{1,2}\/\d{1,2}\/)(\d{4})/, (_, prefix, year) => prefix + (Number(year) > 2400 ? Number(year) - 543 : year));
    return 'You can change your ' + (date[1] === 'ชื่อเล่น' ? 'nickname' : '@username') + ' again on ' + readable + '.';
  }
  if (message.startsWith('ยังไม่พบไฟล์ firebase-service-account.json')) return 'Firebase server credentials were not found. Configure the service-account file and restart the server.';
  if (message.startsWith('ยังไม่ได้ตั้งไฟล์สิทธิ์ Firebase')) return 'Firebase server credentials are not configured. Set GOOGLE_APPLICATION_CREDENTIALS and restart the server.';
  return message;
}
export function applyTranslations(root = document, language = getLanguage()) {
  document.documentElement.lang = language;
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n, {}, language);
  for (const attribute of ['aria-label', 'title', 'placeholder', 'alt']) {
    for (const element of root.querySelectorAll('[data-i18n-' + attribute + ']')) element.setAttribute(attribute, t(element.getAttribute('data-i18n-' + attribute), {}, language));
  }
}
if (typeof document !== 'undefined') applyTranslations();
